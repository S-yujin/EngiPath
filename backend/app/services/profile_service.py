"""Profile service (handoff §16).

Responsible for creating/updating StudentProfile, applying extracted
profile updates from reflections, saving student corrections, and
retrieving the current profile.
"""

from app.models.student import StudentProfile
from app.repositories.student_repository import StudentRepository


class ProfileService:
    def __init__(self, repository: StudentRepository | None = None):
        self.repository = repository or StudentRepository()

    def create_student(
        self,
        major: str | None = None,
        year: int | None = None,
        intro: str | None = None,
        skills: list[str] | None = None,
        interests: list[str] | None = None,
        experiences: list | None = None,
    ) -> StudentProfile:
        return self.repository.create(
            major=major,
            year=year,
            intro=intro,
            skills=skills,
            interests=interests,
            experiences=experiences,
        )

    def get_profile(self, student_id: str) -> StudentProfile | None:
        return self.repository.get(student_id)

    def get_or_404(self, student_id: str) -> StudentProfile:
        profile = self.repository.get(student_id)
        if profile is None:
            raise KeyError(f"Student {student_id} not found")
        return profile

    def apply_profile_updates(self, student_id: str, updates: dict) -> StudentProfile:
        """Merge a partial profile update (e.g. from a reflection) into the
        stored profile. Lists are extended (deduplicated), scalars replaced.
        """
        profile = self.get_or_404(student_id)
        updates = updates or {}

        for field in ("major", "year", "intro", "target_role_id"):
            if field in updates and updates[field] is not None:
                setattr(profile, field, updates[field])

        for field in ("skills", "interests", "unknown_areas"):
            if field in updates and isinstance(updates[field], list):
                current = getattr(profile, field)
                seen = set(current)
                for item in updates[field]:
                    if item not in seen:
                        current.append(item)
                        seen.add(item)

        # Merge experiences by identity (dedupe on (type, title) when title exists).
        if "experiences" in updates and isinstance(updates["experiences"], list):
            existing = profile.experiences
            existing_keys = {
                (e.type, e.title) for e in existing if e.title is not None
            }
            for exp in updates["experiences"]:
                if exp.title is not None and (exp.type, exp.title) in existing_keys:
                    continue
                existing.append(exp)
                if exp.title is not None:
                    existing_keys.add((exp.type, exp.title))

        # Strengths / development areas are lists of ReflectionItems.
        for field in ("strengths", "development_areas"):
            if field in updates and isinstance(updates[field], list):
                current = getattr(profile, field)
                seen_areas = {i.area for i in current}
                for item in updates[field]:
                    if item.area not in seen_areas:
                        current.append(item)
                        seen_areas.add(item.area)

        return self.repository.update_profile(profile)

    def save_correction(self, student_id: str, area: str, context: str) -> StudentProfile:
        """Student add-context feedback: attach context to matching items or
        record it in development areas. The portrait is regenerated by the
        caller via the reflection service.
        """
        profile = self.get_or_404(student_id)
        # Attach context to an existing item if one matches by area.
        for bucket in (profile.strengths, profile.development_areas):
            for item in bucket:
                if item.area.lower() == area.lower():
                    item.evidence.append(context)
                    return self.repository.update_profile(profile)
        # Otherwise record it as an area to develop (with the context as evidence).
        from app.models.reflection import ReflectionItem

        profile.development_areas.append(
            ReflectionItem(
                area=area,
                reason="Student added context during portrait review.",
                evidence=[context],
            )
        )
        return self.repository.update_profile(profile)

    def set_target_role(self, student_id: str, target_role_id: str) -> StudentProfile:
        profile = self.get_or_404(student_id)
        profile.target_role_id = target_role_id
        return self.repository.update_profile(profile)
